	</array>
	<key>connectors</key>
	<dict/>
	<key>workflowMetaData</key>
	<dict>
		<key>serviceInputTypeIdentifier</key>
		<string>com.apple.Automator.nothing</string>
		<key>serviceOutputTypeIdentifier</key>
		<string>com.apple.Automator.nothing</string>
		<key>serviceProcessesInput</key>
		<false/>
		<key>workflowTypeIdentifier</key>
		<string>com.apple.Automator.servicesMenu</string>
	</dict>
</dict>
</plist>
EOF

# Bind ⌘⇧2 to the service and refresh the Services menu.
defaults write pbs NSServicesStatus -dict-add "(null) - $service - runWorkflowAsService" "{ key_equivalent = \"$shortcut\"; enabled_services_menu = 1; }"
/System/Library/CoreServices/pbs -flush
/System/Library/CoreServices/pbs -update

echo "Installed. Select text on screen with ⌘⇧2 to copy it."
echo "If the shortcut doesn't work, log out and back in, then check"
echo "System Settings → Keyboard → Keyboard Shortcuts → Services → Text."
