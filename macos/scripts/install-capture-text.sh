#!/bin/bash
# Installs capture-text: select a screen area with ⌘⇧2 and copy its text.
# macOS only. Needs the Xcode command line tools for swiftc.
set -euo pipefail

if [ "$(uname -s)" != "Darwin" ]; then
  echo "install-capture-text.sh only supports macOS" >&2
  exit 1
fi

here=$(cd "$(dirname "$0")" && pwd)
bin="$HOME/.local/bin"
workflow="$HOME/Library/Services/Capture Text.workflow"
service="Capture Text"
# Services shortcut format: @ = Command, $ = Shift, 2 = key.
shortcut='@$2'

mkdir -p "$bin"
swiftc -O "$here/capture-text-ocr.swift" -o "$bin/capture-text-ocr"
install -m 755 "$here/capture-text" "$bin/capture-text"

# A Quick Action is a Services workflow. Recreate it so re-running is safe.
rm -rf "$workflow"
mkdir -p "$workflow/Contents"

cat > "$workflow/Contents/Info.plist" <<'EOF'
